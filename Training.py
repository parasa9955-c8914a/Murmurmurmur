def clean_audio(
    input_path: str,
    output_path: str,
    top_db: float = 20.0,
    target_lufs: float = -23.0,
):
    input_path = Path(input_path)
    output_path = Path(output_path)

    y, sr = librosa.load(str(input_path), sr=None, mono=False)
    original_length = y.shape[-1]

    if y.ndim == 2:
        y_mono = librosa.to_mono(y)
    else:
        y_mono = y

    y_mono = np.nan_to_num(y_mono, nan=0.0, posinf=0.0, neginf=0.0)

    _, intervals = librosa.effects.trim(y_mono, top_db=top_db)
    start, end = intervals[0], intervals[1]

    if y.ndim == 2:
        y_trimmed = y[:, start:end]
    else:
        y_trimmed = y[start:end]

    trimmed_length = y_trimmed.shape[-1]
    pad_width = original_length - trimmed_length

    if pad_width > 0:
        if y.ndim == 2:
            y_padded = np.pad(y_trimmed, ((0, 0), (0, pad_width)), mode="constant")
        else:
            y_padded = np.pad(y_trimmed, (0, pad_width), mode="constant")
    else:
        y_padded = y_trimmed[..., :original_length]

    y_padded = np.nan_to_num(y_padded, nan=0.0, posinf=0.0, neginf=0.0)

    rms = np.sqrt(np.mean(y_padded ** 2))

    if rms > 0:
        target_rms = 10 ** (target_lufs / 20.0)
        gain = target_rms / rms
        y_normalized = np.clip(y_padded * gain, -1.0, 1.0)
    else:
        y_normalized = y_padded

    if y_normalized.ndim == 2:
        y_out = y_normalized.T
    else:
        y_out = y_normalized

    output_path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(str(output_path), y_out, sr)

    print(f"Done: {input_path.name}")
    print(f"Original length : {original_length / sr:.3f}s")
    print(f"Trimmed content : {trimmed_length / sr:.3f}s")
    print(f"Pad added       : {pad_width / sr:.3f}s")
    print(f"RMS before      : {rms:.6f}")
    print(f"Saved to        : {output_path}")

def batch_clean(input_dir: str, output_dir: str, extensions=(".wav", ".flac", ".mp3")):
    input_dir = Path(input_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    files = [
        f for f in input_dir.rglob("*")
        if f.suffix.lower() in extensions
    ]
    print(f"Found {len(files)} file(s) in {input_dir}\n")

    for f in files:
        out = output_dir / f.relative_to(input_dir).with_suffix(".wav")
        out.parent.mkdir(parents=True, exist_ok=True)
        try:
            clean_audio(str(f), str(out))
        except Exception as e:
            print(f"Error {f.name}: {e}")

