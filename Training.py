class ReduceLROnPlateauCallback(TrainerCallback):
    def __init__(
        self,
        factor=0.5,
        patience=1,
        min_lr=1e-7
    ):
        self.factor = factor
        self.patience = patience
        self.min_lr = min_lr
        self.scheduler = None

    def on_train_begin(
        self,
        args,
        state,
        control,
        **kwargs
    ):

        optimizer = kwargs["optimizer"]
        self.scheduler = ReduceLROnPlateau(
            optimizer,
            mode="min",
            factor=self.factor,
            patience=self.patience,
            min_lr=self.min_lr
        )

    def on_evaluate(
        self,
        args,
        state,
        control,
        metrics,
        **kwargs
    ):
        if "eval_loss" in metrics:
            self.scheduler.step(
                metrics["eval_loss"]
            )

