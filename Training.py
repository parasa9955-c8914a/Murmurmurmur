def eval_model(model, hf_valid_dataset, feature_extractor=None, batch_size=8, device="cuda"):
    model.eval()
    model.to(device)

    valid_loader = DataLoader(
        hf_valid_dataset,
        batch_size=batch_size,
        shuffle=False
    )
    total = 0
    correct = 0
    total_loss = 0.0

    loss_fn = torch.nn.CrossEntropyLoss()
    with torch.no_grad():
        for batch in tqdm(valid_loader, desc="Evaluating"):
            # common HF dataset keys: input_values / pixel_values / input_features
            if "input_values" in batch:
                inputs = batch["input_values"].to(device)
                outputs = model(input_values=inputs, labels=batch["label"].to(device))
            elif "pixel_values" in batch:
                inputs = batch["pixel_values"].to(device)
                outputs = model(pixel_values=inputs, labels=batch["label"].to(device))
            elif "input_features" in batch:
                inputs = batch["input_features"].to(device)
                outputs = model(input_features=inputs, labels=batch["label"].to(device))
            else:
                raise ValueError(f"Unknown input keys: {batch.keys()}")

            labels = batch["label"].to(device)
            loss = outputs.loss
            logits = outputs.logits
            preds = torch.argmax(logits, dim=-1)
            total_loss += loss.item()
            correct += (preds == labels).sum().item()
            total += labels.size(0)

    avg_loss = total_loss / len(valid_loader)
    accuracy = correct / total
    return {
        "eval_loss": avg_loss,
        "eval_accuracy": accuracy
    }

